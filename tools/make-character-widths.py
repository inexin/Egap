"""Writes src/Egap.Spreadsheets/Printing/CharacterWidths.Table.cs from Excel's measured widths.

tools/excel-character-width-oracle.ps1 has Excel AutoFit runs of 40 copies of each character and records the column widths
in pixels in tests/Egap.Spreadsheets.Tests/Oracle/character-widths.excel.tsv. Excel AutoFits a column to 29/28 of the text's
width in whole pixels per character, plus 5 pixels of padding, so each character's pixels are (width - 5) * 28 / 29 / 40,
rounded. Each font's widths go into the table as one string, a character per width: '0' plus the pixels.

Run it as:
  python tools/make-character-widths.py
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, 'tests', 'Egap.Spreadsheets.Tests', 'Oracle', 'character-widths.excel.tsv')
TARGET = os.path.join(ROOT, 'src', 'Egap.Spreadsheets', 'Printing', 'CharacterWidths.Table.cs')
REPEAT = 40


def main():
    with open(SOURCE, encoding='utf-8') as f:
        lines = [line.rstrip('\n') for line in f if line.strip()]
    header = lines[0]
    chars = [int(c) for c in header.split('characters ', 1)[1].split(',')]
    rows = []
    for line in lines[1:]:
        font, size, bold, widths = line.split('\t')
        pixels = [int(p) for p in widths.split(',')]
        assert len(pixels) == len(chars), font
        text = ''
        for p in pixels:
            width = round((p - 5) * 28 / 29 / REPEAT)
            assert 0 <= width <= 42, (font, size, p)
            text += chr(ord('0') + width)
        rows.append((font, size, bold, text))

    out = []
    out.append('// <auto-generated>Written by tools/make-character-widths.py from Oracle/character-widths.excel.tsv; do not edit.</auto-generated>')
    out.append('')
    out.append('namespace Egap.Spreadsheets.Printing;')
    out.append('')
    out.append('internal static partial class CharacterWidths')
    out.append('{')
    out.append('    /// <summary>The characters the table measures, in its order.</summary>')
    out.append('    private const string Measured = "' + ''.join('\\u%04X' % c if c > 126 or c in (34, 92) else chr(c) for c in chars) + '";')
    out.append('')
    out.append("    /// <summary>Each font's widths in pixels at 96 dpi, as '0' plus the pixels per character of <see cref=\"Measured\"/>.</summary>")
    out.append('    private static readonly (string Font, double Size, bool Bold, string Widths)[] Table =')
    out.append('    [')
    for font, size, bold, text in rows:
        out.append('        ("%s", %s, %s, "%s"),' % (font, size, 'true' if bold == '1' else 'false', text))
    out.append('    ];')
    out.append('}')
    with open(TARGET, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
