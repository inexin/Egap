"""Generates src/Egap.Spreadsheets/Printing/PivotStyles.g.cs from ECMA-376's preset table styles.

The styles ship with ECMA-376 Part 1 (OfficeOpenXML-SpreadsheetMLStyles.zip, presetTableStyles.xml). The file is not kept in
this repository; pass its path:

    python tools/gen-pivot-styles.py path/to/presetTableStyles.xml

Only the 84 pivot styles (PivotStyleLight1 to PivotStyleDark28) are kept. Each differential format becomes one compact text,
its parts separated by spaces, which PivotStyles parses the first time a table asks for its style:

    b                   bold
    cT[~TINT]           the font colour: theme colour T, lightened or darkened by TINT
    fT[~TINT]           a solid fill of that colour
    ES[T[~TINT]]        a border edge E (L left, R right, T top, B bottom, V inside vertical, H inside horizontal) of style
                        S (t thin, m medium, d double, 0 none) and colour

Each style is a list of "element format" pairs, the element as ECMA-376 names it (18.18.75 ST_TableStyleType) and the format
an index into the formats.
"""

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "Egap.Spreadsheets" / "Printing" / "PivotStyles.g.cs"
EDGES = {"left": "L", "right": "R", "top": "T", "bottom": "B", "vertical": "V", "horizontal": "H"}
STYLES = {"thin": "t", "medium": "m", "double": "d", None: "0"}


def color(element):
    if element is None:
        return ""
    if set(element.attrib) - {"theme", "tint"}:
        raise ValueError(f"a colour this script does not know: {element.attrib}")
    text = element.get("theme")
    tint = element.get("tint")
    if tint is not None and float(tint) != 0:
        text += "~" + repr(round(float(tint), 6))
    return text


def compact(dxf):
    parts = []
    font = dxf.find("font")
    if font is not None:
        for child in font:
            if child.tag == "b":
                parts.append("b")
            elif child.tag == "color":
                parts.append("c" + color(child))
            else:
                raise ValueError(f"a font part this script does not know: {child.tag}")
    fill = dxf.find("fill")
    if fill is not None:
        pattern = fill.find("patternFill")
        if pattern.get("patternType") != "solid":
            raise ValueError("a fill that is not solid")
        parts.append("f" + color(pattern.find("bgColor") if pattern.find("bgColor") is not None else pattern.find("fgColor")))
    border = dxf.find("border")
    if border is not None:
        for edge in border:
            style = edge.get("style")
            parts.append(EDGES[edge.tag] + STYLES[style] + (color(edge.find("color")) if style else ""))
    for child in dxf:
        if child.tag not in ("font", "fill", "border"):
            raise ValueError(f"a format part this script does not know: {child.tag}")
    return " ".join(parts)


def main():
    root = ET.parse(sys.argv[1]).getroot()
    formats = []
    index = {}
    styles = []
    for style in root:
        if not style.tag.startswith("PivotStyle"):
            continue
        dxfs = [compact(d) for d in style.find("dxfs")]
        table = style.find("tableStyles/tableStyle")
        elements = []
        for element in table:
            if element.get("size") not in (None, "1"):
                raise ValueError("a stripe size this script does not know")
            text = dxfs[int(element.get("dxfId"))]
            if text not in index:
                index[text] = len(formats)
                formats.append(text)
            elements.append(f"{element.get('type')} {index[text]}")
        styles.append((style.tag, ",".join(elements)))

    def key(item):
        name = item[0][len("PivotStyle"):]
        kind = name.rstrip("0123456789")
        return (["Light", "Medium", "Dark"].index(kind), int(name[len(kind):]))

    styles.sort(key=key)
    lines = [
        "// <auto-generated>",
        "// Made by tools/gen-pivot-styles.py from ECMA-376 Part 1's presetTableStyles.xml; do not edit by hand.",
        "// </auto-generated>",
        "",
        "namespace Egap.Spreadsheets.Printing;",
        "",
        "internal static partial class PivotStyles",
        "{",
        "    private static readonly string[] Formats =",
        "    [",
    ]
    lines += [f'        "{f}",' for f in formats]
    lines += ["    ];", "", "    private static readonly (string Name, string Elements)[] Presets =", "    ["]
    lines += [f'        ("{name}", "{elements}"),' for name, elements in styles]
    lines += ["    ];", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(styles)} styles, {len(formats)} formats -> {OUT}")


if __name__ == "__main__":
    main()
