"""Generates src/Egap.Documents/DrawingML/PresetGeometries.g.cs from ECMA-376's preset shape definitions.

The definitions ship with ECMA-376 Part 1 (OfficeOpenXML-DrawingMLGeometries.zip, presetShapeDefinitions.xml). The file is not
kept in this repository; pass its path:

    python tools/gen-preset-shapes.py path/to/presetShapeDefinitions.xml

Each preset becomes one compact text, one item per line, which PresetGeometries parses the first time a shape asks for it:

    a NAME FORMULA...       an adjust value (avLst) and its default
    g NAME FORMULA...       a guide (gdLst)
    p W H FILL STROKE       a path; W and H are - when the path uses the shape's own size; FILL is none, norm, lighten,
                            lightenLess, darken or darkenLess; STROKE is 1 or 0
    M X Y / L X Y           moveTo, lnTo
    A WR HR ST SW           arcTo
    Q X1 Y1 X Y             quadBezTo
    C X1 Y1 X2 Y2 X Y       cubicBezTo
    Z                       close
    r L T R B               the text rectangle

Connection sites and adjust handles are not kept: nothing draws them.
"""

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

A = "{http://schemas.openxmlformats.org/drawingml/2006/main}"
OUT = Path(__file__).resolve().parent.parent / "src" / "Egap.Documents" / "DrawingML" / "PresetGeometries.g.cs"


UP_ARROW = "\\n".join([
    "a adj1 val 50000",
    "a adj2 val 50000",
    "g maxAdj2 */ 100000 h ss",
    "g a1 pin 0 adj1 100000",
    "g a2 pin 0 adj2 maxAdj2",
    "g dy2 */ ss a2 100000",
    "g y2 +- t dy2 0",
    "g dx1 */ w a1 200000",
    "g x1 +- hc 0 dx1",
    "g x2 +- hc dx1 0",
    "g dy1 */ x1 dy2 wd2",
    "g y1 +- y2 0 dy1",
    "p - - norm 1",
    "M l y2",
    "L hc t",
    "L r y2",
    "L x2 y2",
    "L x2 b",
    "L x1 b",
    "L x1 y2",
    "Z",
    "r x1 y1 x2 b",
])


def point(pt):
    return f"{pt.get('x')} {pt.get('y')}"


def preset(shape):
    lines = []
    for list_name, tag in (("avLst", "a"), ("gdLst", "g")):
        for gd in shape.findall(f"{A}{list_name}/{A}gd"):
            lines.append(f"{tag} {gd.get('name')} {' '.join(gd.get('fmla').split())}")
    for path in shape.findall(f"{A}pathLst/{A}path"):
        stroke = "0" if path.get("stroke") == "false" else "1"
        lines.append(f"p {path.get('w', '-')} {path.get('h', '-')} {path.get('fill', 'norm')} {stroke}")
        for command in path:
            name = command.tag[len(A):]
            pts = command.findall(f"{A}pt")
            if name == "moveTo":
                lines.append("M " + point(pts[0]))
            elif name == "lnTo":
                lines.append("L " + point(pts[0]))
            elif name == "arcTo":
                lines.append(f"A {command.get('wR')} {command.get('hR')} {command.get('stAng')} {command.get('swAng')}")
            elif name == "quadBezTo":
                lines.append("Q " + " ".join(point(p) for p in pts))
            elif name == "cubicBezTo":
                lines.append("C " + " ".join(point(p) for p in pts))
            elif name == "close":
                lines.append("Z")
            else:
                raise ValueError(f"unknown path command {name}")
    rect = shape.find(f"{A}rect")
    if rect is not None:
        lines.append(f"r {rect.get('l')} {rect.get('t')} {rect.get('r')} {rect.get('b')}")
    return "\\n".join(lines)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    root = ET.parse(sys.argv[1]).getroot()
    definitions = {}
    for shape in root:
        name = shape.tag
        text = preset(shape)
        if name in definitions and definitions[name] != text:
            raise ValueError(f"{name} is defined twice, differently")
        definitions[name] = text
    # The 5th edition's file lists upDownArrow twice, the same both times, where upArrow belongs (ST_ShapeType has upArrow).
    # upArrow is downArrow upside down; written here from downArrow's guides.
    if "upArrow" not in definitions:
        definitions["upArrow"] = UP_ARROW
    shapes = sorted(definitions.items())
    out = [
        "// <auto-generated>",
        "// Generated by tools/gen-preset-shapes.py from presetShapeDefinitions.xml of ECMA-376 Part 1 (Ecma International);",
        "// see THIRD-PARTY-NOTICES.md. Do not edit by hand.",
        "// </auto-generated>",
        "",
        "namespace Egap.Documents.DrawingML;",
        "",
        "internal static partial class PresetGeometries",
        "{",
        f"    /// <summary>The {len(shapes)} preset geometries of ECMA-376, by name, in the compact form tools/gen-preset-shapes.py writes.</summary>",
        "    private static readonly (string Name, string Definition)[] Definitions =",
        "    [",
    ]
    for name, text in shapes:
        out.append(f'        ("{name}", "{text}"),')
    out += ["    ];", "}", ""]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(shapes)} presets written to {OUT}")


if __name__ == "__main__":
    main()
