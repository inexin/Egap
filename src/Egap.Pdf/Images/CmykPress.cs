    /// <summary>Converts ink amounts (0 = no ink, 1 = full) to sRGB, each 0 to 1.</summary>
    public static void ToRgb(double c, double m, double y, double k, Span<double> rgb)
    {
        Span<double> cp = [1, c, c * c, c * c * c, c * c * c * c];
        Span<double> mp = [1, m, m * m, m * m * m, m * m * m * m];
        Span<double> yp = [1, y, y * y, y * y * y, y * y * y * y];
        Span<double> kp = [1, k, k * k, k * k * k, k * k * k * k];
        double r = 0, g = 0, b = 0;
        for (int i = 0; i < Terms.Length; i++)
        {
            (int pc, int pm, int py, int pk) = Terms[i];
            double f = cp[pc] * mp[pm] * yp[py] * kp[pk];
            r += Red[i] * f;
            g += Green[i] * f;
            b += Blue[i] * f;
        }

        rgb[0] = Math.Clamp(r, 0, 1);
        rgb[1] = Math.Clamp(g, 0, 1);
        rgb[2] = Math.Clamp(b, 0, 1);
    }
